// Testa as migrações SQL num Postgres 17 real (PGlite, em memória) que imita o Supabase:
// papéis anon/authenticated, auth.uid(), extensão pgcrypto e a base de dados "aberta" como está hoje.
// Uso: node sql.test.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PGlite } from "@electric-sql/pglite";
import { pgcrypto } from "@electric-sql/pglite/contrib/pgcrypto";
import { criarRelatorio } from "./lib/relatorio.mjs";

const AQUI = path.dirname(fileURLToPath(import.meta.url));
const MIG = path.join(AQUI, "..", "supabase", "migracoes");
const sqlDe = (f) => fs.readFileSync(path.join(MIG, f), "utf8");

const TREINADOR = "00000000-0000-4000-8000-000000000001";
const INTRUSO = "00000000-0000-4000-8000-000000000099";

// Estado atual da produção (inferido do código + verificação feita à BD real).
const ESQUEMA_ATUAL = `
create role anon nologin; create role authenticated nologin; create role service_role nologin bypassrls;
create schema auth; create schema extensions;
create extension pgcrypto schema extensions;
create table auth.users (id uuid primary key, email text);
create function auth.uid() returns uuid language sql stable as
  $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
grant usage on schema public, auth, extensions to anon, authenticated;
grant execute on all functions in schema auth to anon, authenticated;
alter default privileges in schema public grant all on tables to anon, authenticated;
alter default privileges in schema public grant all on sequences to anon, authenticated;

create table socios (id bigint generated by default as identity primary key, nome text, email text,
  telemovel text, password text, modalidade text, treinador text, estado text, data_inscricao date,
  graduacao text, federacao text, data_ultima_graduacao date, data_inativo date, data_reentrada date,
  regulamento_aceite boolean default false, foto_url text);
create table mensalidades (id bigint generated by default as identity primary key, socio_id bigint,
  mes_ano text, valor numeric, estado text, tipo text, dia_aula text, hora_aula text);
create table aulas_particulares (id bigint generated by default as identity primary key, socio_id bigint,
  data_aula date, hora_aula time, estado text, valor numeric, pago boolean default false,
  created_at timestamptz default now());
create table notificacoes (id bigint generated by default as identity primary key, socio_id bigint,
  titulo text, mensagem text, lida boolean default false, created_at timestamptz default now());
create table push_subscriptions (socio_id bigint unique, subscricao text);
create table admin_push_subscriptions (id bigint generated by default as identity primary key,
  treinador_email text, subscricao text);
create table despesas (id bigint generated by default as identity primary key, descricao text,
  categoria text, data date, valor numeric, treinador text);
create table sistema_ping (id int primary key); insert into sistema_ping values (1);

-- Política antiga permissiva (simula o que deixa o público ler tudo hoje).
alter table despesas enable row level security;
create policy "antiga_publica" on despesas for all using (true);

-- Funções antigas do portal (aceitam qualquer ID: é a falha).
create function assinar_regulamento(atleta_id bigint) returns void language sql security definer as
  $$ update socios set regulamento_aceite = true where id = atleta_id $$;
create function alterar_password_atleta(atleta_id bigint, nova_password text) returns void language sql security definer as
  $$ update socios set password = nova_password where id = atleta_id $$;

insert into auth.users values ('${TREINADOR}', 'bogas@teste.pt'), ('00000000-0000-4000-8000-000000000002', 'antonio@teste.pt');
insert into socios (id, nome, email, telemovel, password, estado) values
  (1, 'Ana Teste', 'Ana@Teste.pt', '912345678', 'segredo123', 'Ativo'),
  (2, 'Bruno Teste', 'bruno@teste.pt', '934567890', null, 'Ativo');
insert into mensalidades (socio_id, mes_ano, valor, estado, tipo) values
  (1, '2026-11', 35, 'Pago', 'Mensalidade'), (2, '2026-11', 35, 'Pendente', 'Mensalidade');
insert into notificacoes (socio_id, titulo, mensagem) values (1, 'Olá', 'Para a Ana'), (2, 'Olá', 'Para o Bruno');
`;

const db = new PGlite({ extensions: { pgcrypto } });
const r = criarRelatorio("SQL (migrações)");

async function como(papel, sub, fn) {
  await db.exec(`reset role; select set_config('request.jwt.claim.sub', '${sub || ""}', false); set role ${papel};`);
  try {
    return await fn();
  } finally {
    await db.exec("reset role;");
  }
}
const q = async (sql, params) => (await db.query(sql, params)).rows;
async function falha(sql, params) {
  try {
    await db.query(sql, params);
    return null;
  } catch (e) {
    return e.message;
  }
}

await db.exec(ESQUEMA_ATUAL);

// ---------------- FASE 1 ----------------
await db.exec(sqlDe("01_preparar.sql"));
await db.exec(sqlDe("01_preparar.sql"));
r.ok("Fase 1 corre sem erros e é idempotente (2x)", true);

await como("anon", null, async () => {
  const s = await q("select id, password from socios where id = 1");
  r.ok("Fase 1 não parte o site antigo: anon ainda lê socios (login antigo funciona)", s[0]?.password === "segredo123");
  const erro = await falha("select * from treinadores");
  r.ok("Tabela treinadores fechada ao público", !!erro, erro);
});

const treinadores = await q("select nome from treinadores order by nome");
r.ok("Treinadores criados a partir das contas de login (regra 'antonio')", JSON.stringify(treinadores.map((t) => t.nome)) === '["António","Bogas"]', JSON.stringify(treinadores));

const hash = await q("select password_hash from socios where id = 1");
r.ok("Password em texto convertida para hash bcrypt", hash[0].password_hash?.startsWith("$2"));

// ---------------- PORTAL ----------------
async function login(email, pass) {
  return como("anon", null, async () => (await q("select portal_login($1, $2) as r", [email, pass]))[0].r);
}

const l1 = await login("ana@teste.pt ", "segredo123");
r.ok("Login com password (email sem maiúsculas/espaços)", !!l1?.token && l1.socio.id === 1);
r.ok("Login NÃO devolve password nem hash", l1 && !("password" in l1.socio) && !("password_hash" in l1.socio), JSON.stringify(l1?.socio));
r.ok("Password errada -> null", (await login("ana@teste.pt", "errada")) === null);
r.ok("Email inexistente -> null (não revela se existe)", (await login("ninguem@teste.pt", "x")) === null);
const l2 = await login("bruno@teste.pt", "934567890");
r.ok("Regra antiga mantida: sem password, entra com o telemóvel", l2?.socio?.id === 2);

const tokenAna = l1.token;
const tokenBruno = l2.token;
const resumo = await como("anon", null, async () => (await q("select portal_resumo($1, '2026-11', '2026-11-01') as r", [tokenAna]))[0].r);
r.ok("portal_resumo devolve só dados da Ana", resumo.socio.id === 1 && resumo.notificacoes.length === 1 && resumo.notificacoes[0].mensagem === "Para a Ana");
r.ok("portal_resumo traz a fatura do mês", resumo.faturas_mes[0]?.estado === "Pago");

const erroToken = await como("anon", null, () => falha("select portal_resumo('token-inventado-com-mais-de-trinta-chars', '2026-11', '2026-11-01')"));
r.ok("Token inventado é recusado", erroToken?.includes("SESSAO_INVALIDA"), erroToken);
const erroId = await como("anon", null, () => falha("select portal_historico('1')"));
r.ok("Já não é possível entrar só com o ID do atleta", erroId?.includes("SESSAO_INVALIDA"), erroId);

const notifBruno = (await q("select id from notificacoes where socio_id = 2"))[0].id;
const apagou = await como("anon", null, async () => (await q("select portal_apagar_notificacao($1, $2) as r", [tokenAna, notifBruno]))[0].r);
r.ok("Ana NÃO consegue apagar notificação do Bruno", apagou === false && (await q("select 1 from notificacoes where id = $1", [notifBruno])).length === 1);

const erroSemana = await como("anon", null, () => falha("select portal_pedir_aula($1, '2026-11-11', '15:00', '2026-11-01')", [tokenAna]));
r.ok("Pedido de aula a uma quarta-feira é recusado no servidor", erroSemana?.includes("SO_FIM_DE_SEMANA"), erroSemana);
const erroHora = await como("anon", null, () => falha("select portal_pedir_aula($1, '2026-11-14', '11:00', '2026-11-01')", [tokenAna]));
r.ok("Sábado antes das 13h é recusado", erroHora?.includes("FORA_DE_HORAS"), erroHora);
const pedido = await como("anon", null, async () => (await q("select portal_pedir_aula($1, '2026-11-14', '14:00', '2026-11-01') as r", [tokenAna]))[0].r);
r.ok("Pedido de aula ao sábado 14h cria aula + notificação", pedido.nome === "Ana Teste" && (await q("select 1 from notificacoes where socio_id=1 and titulo like 'Aula Pendente%'")).length === 1);

await como("anon", null, () => q("select portal_alterar_password($1, 'novapass')", [tokenAna]));
r.ok("Alterar password: a antiga deixa de funcionar", (await login("ana@teste.pt", "segredo123")) === null);
r.ok("Alterar password: a nova funciona", !!(await login("ana@teste.pt", "novapass"))?.token);
r.ok("Alterar password não guarda texto simples", (await q("select password from socios where id = 1"))[0].password === null);

await como("anon", null, () => q("select portal_guardar_push($1, '{\"endpoint\":\"x\"}')", [tokenBruno]));
await como("anon", null, () => q("select portal_guardar_push($1, '{\"endpoint\":\"y\"}')", [tokenBruno]));
const subs = await q("select subscricao from push_subscriptions where socio_id = 2");
r.ok("Subscrição push: 1 por atleta, a última substitui", subs.length === 1 && subs[0].subscricao.includes("y"));
r.ok("portal_tem_push", (await como("anon", null, async () => (await q("select portal_tem_push($1) as r", [tokenBruno]))[0].r)) === true);

await como("anon", null, () => q("select portal_logout($1)", [tokenBruno]));
const erroLogout = await como("anon", null, () => falha("select portal_historico($1)", [tokenBruno]));
r.ok("Depois do logout o token deixa de valer", erroLogout?.includes("SESSAO_INVALIDA"));

for (let i = 0; i < 8; i++) await login("bruno@teste.pt", "errada");
const erroForca = await como("anon", null, () => falha("select portal_login('bruno@teste.pt', '934567890')"));
r.ok("Após 8 falhas em 15 min o login bloqueia (anti-força-bruta)", erroForca?.includes("DEMASIADAS_TENTATIVAS"), erroForca);
await q("delete from login_tentativas");

// ---------------- FASE 2 ----------------
await db.exec(sqlDe("02_fechar_acesso.sql"));
await db.exec(sqlDe("02_fechar_acesso.sql"));
r.ok("Fase 2 corre sem erros e é idempotente (2x)", true);
r.ok("Nenhuma tabela pública fica sem RLS", (await q("select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind='r' and not c.relrowsecurity")).length === 0);
r.ok("Nenhuma password em texto simples", (await q("select 1 from socios where password is not null")).length === 0);

for (const t of ["socios", "mensalidades", "notificacoes", "aulas_particulares", "despesas", "push_subscriptions", "admin_push_subscriptions", "sessoes_atleta", "treinadores"]) {
  const erro = await como("anon", null, () => falha(`select * from ${t}`));
  r.ok(`Público (anon) NÃO lê ${t}`, /permission denied/.test(erro || ""), erro || "leu!");
}
const erroInsert = await como("anon", null, () => falha("insert into notificacoes (socio_id, titulo) values (1, 'falsa')"));
r.ok("Público NÃO cria notificações falsas", /permission denied|row-level security/.test(erroInsert || ""), erroInsert);
r.ok("Ping público continua a funcionar", (await como("anon", null, () => q("select id from sistema_ping"))).length === 1);

const erroAntiga = await como("anon", null, () => falha("select alterar_password_atleta(1, 'hack')"));
r.ok("Função antiga alterar_password_atleta bloqueada ao público", /permission denied/.test(erroAntiga || ""), erroAntiga);
const erroAntiga2 = await como("anon", null, () => falha("select assinar_regulamento(1)"));
r.ok("Função antiga assinar_regulamento bloqueada ao público", !!erroAntiga2);

const l3 = await login("ana@teste.pt", "novapass");
r.ok("Portal continua a funcionar depois da fase 2", !!l3?.token);
const l4 = await login("bruno@teste.pt", "934567890");
r.ok("Login com telemóvel continua a funcionar depois da fase 2", !!l4?.token);

const nSocios = await como("authenticated", TREINADOR, () => q("select count(*)::int n from socios"));
r.ok("Treinador lê todos os sócios", nSocios[0].n === 2);
r.ok("meu_treinador() devolve o nome", (await como("authenticated", TREINADOR, () => q("select meu_treinador() n")))[0].n === "Bogas");
const nIntruso = await como("authenticated", INTRUSO, () => q("select count(*)::int n from socios"));
r.ok("Conta com login que NÃO é treinador não vê nada", nIntruso[0].n === 0);
const erroIntrusoRpc = await como("authenticated", INTRUSO, () => falha("select aprovar_aula(1, 20)"));
r.ok("Conta não-treinador não aprova aulas", erroIntrusoRpc?.includes("SEM_PERMISSAO"), erroIntrusoRpc);

// ---------------- APROVAR / FATURAR (bug das 2 aulas no mesmo mês) ----------------
const [a1] = await q("insert into aulas_particulares (socio_id, data_aula, hora_aula, estado) values (2, '2026-11-07', '14:00', 'Pendente') returning id");
const [a2] = await q("insert into aulas_particulares (socio_id, data_aula, hora_aula, estado) values (2, '2026-11-21', '15:00', 'Pendente') returning id");
await como("authenticated", TREINADOR, async () => {
  await q("select aprovar_aula($1, 25)", [a1.id]);
  await q("select aprovar_aula($1, 30)", [a2.id]);
});
const faturasAula = await q("select aula_id, estado, valor::int v, dia_aula, mes_ano from mensalidades where tipo='Aula Particular' order by aula_id");
r.ok("Aprovar 2 aulas no mesmo mês cria 2 faturas pendentes, cada uma ligada à sua aula",
  faturasAula.length === 2 && faturasAula.every((f) => f.estado === "Pendente") && faturasAula[0].dia_aula === "07/11/2026" && faturasAula[0].mes_ano === "2026-11", JSON.stringify(faturasAula));

await como("authenticated", TREINADOR, () => q("select faturar_aula($1, 30)", [a2.id]));
const depois = await q("select aula_id, estado from mensalidades where tipo='Aula Particular' order by aula_id");
r.ok("Faturar a 2ª aula marca como paga SÓ a fatura dela (antes marcava a errada ou duplicava)",
  depois.length === 2 && depois.find((f) => Number(f.aula_id) === Number(a2.id)).estado === "Pago" && depois.find((f) => Number(f.aula_id) === Number(a1.id)).estado === "Pendente", JSON.stringify(depois));

// Registo antigo sem aula_id (criado pelo site antigo): faturar encontra-o pelo dia.
const [a3] = await q("insert into aulas_particulares (socio_id, data_aula, hora_aula, estado, valor) values (1, '2026-10-04', '16:00', 'Aceite', 20) returning id");
await q("insert into mensalidades (socio_id, mes_ano, dia_aula, tipo, estado, valor) values (1, '2026-10', '04/10/2026', 'Aula Particular', 'Pendente', 20)");
await como("authenticated", TREINADOR, () => q("select faturar_aula($1, 20)", [a3.id]));
const legado = await q("select estado, aula_id from mensalidades where socio_id = 1 and mes_ano = '2026-10'");
r.ok("Faturas antigas (sem aula_id) são encontradas e ligadas, sem duplicar", legado.length === 1 && legado[0].estado === "Pago" && Number(legado[0].aula_id) === Number(a3.id), JSON.stringify(legado));

// Atomicidade: se a fatura falhar, a aula não fica 'Aceite'.
const [a4] = await q("insert into aulas_particulares (socio_id, data_aula, hora_aula, estado) values (2, '2026-11-28', '15:00', 'Pendente') returning id");
await q("alter table mensalidades add constraint teste_falha check (valor < 1000)");
const erroAtomico = await como("authenticated", TREINADOR, () => falha("select aprovar_aula($1, 5000)", [a4.id]));
const estadoA4 = (await q("select estado from aulas_particulares where id = $1", [a4.id]))[0].estado;
r.ok("Aprovar é 'tudo ou nada': se a fatura falha, a aula continua Pendente", !!erroAtomico && estadoA4 === "Pendente", estadoA4);

// ---------------- EMERGÊNCIA ----------------
await db.exec(sqlDe("99_emergencia_reverter_fase2.sql"));
r.ok("Script de emergência corre sem erros", true);
r.ok("Depois da emergência o portal novo continua a funcionar", !!(await login("ana@teste.pt", "novapass"))?.token);

process.exitCode = r.fim() ? 0 : 1;
