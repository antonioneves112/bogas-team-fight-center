-- -------------------------------------------------------------------------
-- 1. TABELAS
-- -------------------------------------------------------------------------
create table if not exists public.produtos (
  id bigint generated by default as identity primary key,
  nome text not null,
  categoria text not null default 'Outros',
  preco_compra numeric(10, 2) not null default 0 check (preco_compra >= 0),
  preco_venda numeric(10, 2) not null default 0 check (preco_venda >= 0),
  stock_minimo int not null default 2 check (stock_minimo >= 0),
  ativo boolean not null default true,
  criado_em timestamptz not null default now()
);

-- Variantes: tamanho (S/M/L), onças das luvas (10oz/12oz) ou "Único".
-- Cada variante tem o seu próprio stock.
create table if not exists public.produto_variantes (
  id bigint generated by default as identity primary key,
  produto_id bigint not null references public.produtos (id) on delete cascade,
  nome text not null,
  stock int not null default 0 check (stock >= 0),
  unique (produto_id, nome)
);

create table if not exists public.vendas (
  id bigint generated by default as identity primary key,
  data date not null default current_date,
  socio_id bigint references public.socios (id) on delete set null,
  cliente_nome text not null,
  estado text not null default 'Paga' check (estado in ('Paga', 'Pendente', 'Anulada')),
  metodo text check (metodo in ('Dinheiro', 'MB Way', 'Transferência', 'Multibanco')),
  total numeric(10, 2) not null default 0,
  custo_total numeric(10, 2) not null default 0,
  notas text,
  treinador text,
  criado_em timestamptz not null default now()
);

-- Os itens guardam nome e preços DO MOMENTO da venda: se o preço do produto
-- mudar depois, as vendas antigas e o lucro não mudam.
create table if not exists public.venda_itens (
  id bigint generated by default as identity primary key,
  venda_id bigint not null references public.vendas (id) on delete cascade,
  variante_id bigint references public.produto_variantes (id) on delete set null,
  produto_nome text not null,
  variante_nome text not null,
  quantidade int not null check (quantidade > 0),
  preco_unitario numeric(10, 2) not null check (preco_unitario >= 0),
  custo_unitario numeric(10, 2) not null check (custo_unitario >= 0)
);

-- Histórico de todas as entradas/saídas de stock (auditoria).
create table if not exists public.stock_movimentos (
  id bigint generated by default as identity primary key,
  variante_id bigint not null references public.produto_variantes (id) on delete cascade,
  quantidade int not null,
  motivo text not null check (motivo in ('Stock inicial', 'Entrada', 'Ajuste', 'Venda', 'Anulação')),
  venda_id bigint references public.vendas (id) on delete set null,
  criado_em timestamptz not null default now()
);

create index if not exists produto_variantes_produto_idx on public.produto_variantes (produto_id);
create index if not exists vendas_data_idx on public.vendas (data);
create index if not exists vendas_socio_idx on public.vendas (socio_id);
create index if not exists venda_itens_venda_idx on public.venda_itens (venda_id);
create index if not exists stock_movimentos_variante_idx on public.stock_movimentos (variante_id, criado_em desc);

-- -------------------------------------------------------------------------
-- 2. SEGURANÇA: só treinadores (mesma regra do resto da BD)
-- -------------------------------------------------------------------------
do $$
declare
  t text;
begin
  foreach t in array array['produtos', 'produto_variantes', 'vendas', 'venda_itens', 'stock_movimentos']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('drop policy if exists treinador_total on public.%I', t);
    execute format(
      'create policy treinador_total on public.%I for all to authenticated
         using (public.is_treinador()) with check (public.is_treinador())', t);
  end loop;
end;
$$;

-- -------------------------------------------------------------------------
-- 3. GUARDAR PRODUTO (com variantes) — tudo ou nada
--    p_variantes: [{"id": 5|null, "nome": "M", "stock": 3}]
--    - variante nova: criada com esse stock (movimento "Stock inicial")
--    - variante existente: muda o nome; o stock NÃO muda aqui (usa repor_stock)
--    - variante que desaparece da lista: apagada se nunca foi vendida
-- -------------------------------------------------------------------------
create or replace function public.guardar_produto(
  p_id bigint, p_nome text, p_categoria text, p_preco_compra numeric,
  p_preco_venda numeric, p_stock_minimo int, p_variantes jsonb)
returns bigint
language plpgsql
volatile
security invoker
set search_path = public
as $$
declare
  v_id bigint := p_id;
  v jsonb;
  v_var_id bigint;
  v_ids_mantidos bigint[] := '{}';
begin
  if not public.is_treinador() then raise exception 'SEM_PERMISSAO'; end if;
  if coalesce(trim(p_nome), '') = '' then raise exception 'NOME_EM_FALTA'; end if;
  if p_preco_compra is null or p_preco_compra < 0 or p_preco_venda is null or p_preco_venda < 0 then
    raise exception 'PRECO_INVALIDO';
  end if;
  if p_variantes is null or jsonb_array_length(p_variantes) = 0 then
    raise exception 'SEM_VARIANTES';
  end if;

  if v_id is null then
    insert into public.produtos (nome, categoria, preco_compra, preco_venda, stock_minimo)
    values (trim(p_nome), coalesce(nullif(trim(p_categoria), ''), 'Outros'), p_preco_compra, p_preco_venda, coalesce(p_stock_minimo, 2))
    returning id into v_id;
  else
    update public.produtos
    set nome = trim(p_nome), categoria = coalesce(nullif(trim(p_categoria), ''), 'Outros'),
        preco_compra = p_preco_compra, preco_venda = p_preco_venda,
        stock_minimo = coalesce(p_stock_minimo, stock_minimo)
    where id = v_id;
    if not found then raise exception 'PRODUTO_NAO_ENCONTRADO'; end if;
  end if;

  for v in select * from jsonb_array_elements(p_variantes) loop
    if coalesce(trim(v ->> 'nome'), '') = '' then raise exception 'VARIANTE_SEM_NOME'; end if;

    if nullif(v ->> 'id', '') is not null then
      update public.produto_variantes set nome = trim(v ->> 'nome')
      where id = (v ->> 'id')::bigint and produto_id = v_id
      returning id into v_var_id;
      if v_var_id is null then raise exception 'VARIANTE_NAO_ENCONTRADA'; end if;
    else
      if coalesce((v ->> 'stock')::int, 0) < 0 then raise exception 'STOCK_INVALIDO'; end if;
      insert into public.produto_variantes (produto_id, nome, stock)
      values (v_id, trim(v ->> 'nome'), coalesce((v ->> 'stock')::int, 0))
      returning id into v_var_id;
      if coalesce((v ->> 'stock')::int, 0) > 0 then
        insert into public.stock_movimentos (variante_id, quantidade, motivo)
        values (v_var_id, (v ->> 'stock')::int, 'Stock inicial');
      end if;
    end if;
    v_ids_mantidos := v_ids_mantidos || v_var_id;
  end loop;

  -- Variantes retiradas da lista
  if exists (
    select 1 from public.produto_variantes pv
    join public.venda_itens vi on vi.variante_id = pv.id
    where pv.produto_id = v_id and not (pv.id = any (v_ids_mantidos))
  ) then
    raise exception 'VARIANTE_COM_VENDAS';
  end if;
  delete from public.produto_variantes
  where produto_id = v_id and not (id = any (v_ids_mantidos));

  return v_id;
exception
  when unique_violation then raise exception 'VARIANTE_REPETIDA';
end;
$$;

-- -------------------------------------------------------------------------
-- 4. REPOR / AJUSTAR STOCK
--    Entrada: quantidade positiva (chegou material).
--    Ajuste: positivo ou negativo (contagem, perda, oferta...).
-- -------------------------------------------------------------------------
create or replace function public.repor_stock(p_variante_id bigint, p_quantidade int, p_motivo text)
returns int
language plpgsql
volatile
security invoker
set search_path = public
as $$
declare
  v_stock int;
begin
  if not public.is_treinador() then raise exception 'SEM_PERMISSAO'; end if;
  if p_motivo not in ('Entrada', 'Ajuste') then raise exception 'MOTIVO_INVALIDO'; end if;
  if p_quantidade is null or p_quantidade = 0 then raise exception 'QUANTIDADE_INVALIDA'; end if;
  if p_motivo = 'Entrada' and p_quantidade < 0 then raise exception 'QUANTIDADE_INVALIDA'; end if;

  update public.produto_variantes set stock = stock + p_quantidade
  where id = p_variante_id
  returning stock into v_stock;
  if not found then raise exception 'VARIANTE_NAO_ENCONTRADA'; end if;

  insert into public.stock_movimentos (variante_id, quantidade, motivo)
  values (p_variante_id, p_quantidade, p_motivo);
  return v_stock;
exception
  when check_violation then raise exception 'STOCK_INSUFICIENTE';
end;
$$;

-- -------------------------------------------------------------------------
-- 5. REGISTAR VENDA — tudo ou nada
--    p_itens: [{"variante_id": 3, "quantidade": 2, "preco_unitario": 25}]
--    (preco_unitario é opcional: por defeito usa o preço de venda do produto;
--     serve para descontos)
--    Bloqueia as linhas de stock (FOR UPDATE): duas vendas em simultâneo nunca
--    vendem a mesma última unidade.
-- -------------------------------------------------------------------------
create or replace function public.registar_venda(
  p_itens jsonb, p_socio_id bigint, p_cliente_nome text, p_estado text,
  p_metodo text, p_data date, p_notas text, p_treinador text)
returns bigint
language plpgsql
volatile
security invoker
set search_path = public
as $$
declare
  v_venda bigint;
  v_cliente text;
  i jsonb;
  v_var record;
  v_qtd int;
  v_preco numeric;
  v_total numeric := 0;
  v_custo numeric := 0;
begin
  if not public.is_treinador() then raise exception 'SEM_PERMISSAO'; end if;
  if p_itens is null or jsonb_array_length(p_itens) = 0 then raise exception 'VENDA_VAZIA'; end if;
  if p_estado not in ('Paga', 'Pendente') then raise exception 'ESTADO_INVALIDO'; end if;
  if p_estado = 'Paga' and p_metodo is null then raise exception 'METODO_EM_FALTA'; end if;

  if p_socio_id is not null then
    select nome into v_cliente from public.socios where id = p_socio_id;
    if v_cliente is null then raise exception 'SOCIO_NAO_ENCONTRADO'; end if;
  else
    v_cliente := nullif(trim(coalesce(p_cliente_nome, '')), '');
    if v_cliente is null then raise exception 'CLIENTE_EM_FALTA'; end if;
  end if;

  insert into public.vendas (data, socio_id, cliente_nome, estado, metodo, notas, treinador)
  values (coalesce(p_data, current_date), p_socio_id, v_cliente, p_estado,
          p_metodo, nullif(trim(p_notas), ''), p_treinador)
  returning id into v_venda;

  for i in select * from jsonb_array_elements(p_itens) loop
    v_qtd := (i ->> 'quantidade')::int;
    if v_qtd is null or v_qtd <= 0 then raise exception 'QUANTIDADE_INVALIDA'; end if;

    select pv.id, pv.nome as variante, pv.stock, p.nome as produto, p.preco_venda, p.preco_compra
    into v_var
    from public.produto_variantes pv
    join public.produtos p on p.id = pv.produto_id
    where pv.id = (i ->> 'variante_id')::bigint
    for update of pv;
    if not found then raise exception 'VARIANTE_NAO_ENCONTRADA'; end if;

    if v_var.stock < v_qtd then
      raise exception 'STOCK_INSUFICIENTE: % (%) — só há %', v_var.produto, v_var.variante, v_var.stock;
    end if;

    v_preco := coalesce((i ->> 'preco_unitario')::numeric, v_var.preco_venda);
    if v_preco < 0 then raise exception 'PRECO_INVALIDO'; end if;

    update public.produto_variantes set stock = stock - v_qtd where id = v_var.id;
    insert into public.venda_itens (venda_id, variante_id, produto_nome, variante_nome, quantidade, preco_unitario, custo_unitario)
    values (v_venda, v_var.id, v_var.produto, v_var.variante, v_qtd, v_preco, v_var.preco_compra);
    insert into public.stock_movimentos (variante_id, quantidade, motivo, venda_id)
    values (v_var.id, -v_qtd, 'Venda', v_venda);

    v_total := v_total + v_preco * v_qtd;
    v_custo := v_custo + v_var.preco_compra * v_qtd;
  end loop;

  update public.vendas set total = v_total, custo_total = v_custo where id = v_venda;
  return v_venda;
end;
$$;

-- -------------------------------------------------------------------------
-- 6. MARCAR COMO PAGA / ANULAR (anular devolve o stock)
-- -------------------------------------------------------------------------
create or replace function public.marcar_venda_paga(p_venda_id bigint, p_metodo text)
returns void
language plpgsql
volatile
security invoker
set search_path = public
as $$
begin
  if not public.is_treinador() then raise exception 'SEM_PERMISSAO'; end if;
  if p_metodo is null then raise exception 'METODO_EM_FALTA'; end if;
  update public.vendas set estado = 'Paga', metodo = p_metodo
  where id = p_venda_id and estado = 'Pendente';
  if not found then raise exception 'VENDA_NAO_PENDENTE'; end if;
end;
$$;

create or replace function public.anular_venda(p_venda_id bigint)
returns void
language plpgsql
volatile
security invoker
set search_path = public
as $$
declare
  it record;
begin
  if not public.is_treinador() then raise exception 'SEM_PERMISSAO'; end if;
  perform 1 from public.vendas where id = p_venda_id and estado <> 'Anulada' for update;
  if not found then raise exception 'VENDA_JA_ANULADA'; end if;

  for it in select variante_id, quantidade from public.venda_itens
            where venda_id = p_venda_id and variante_id is not null loop
    update public.produto_variantes set stock = stock + it.quantidade where id = it.variante_id;
    insert into public.stock_movimentos (variante_id, quantidade, motivo, venda_id)
    values (it.variante_id, it.quantidade, 'Anulação', p_venda_id);
  end loop;

  update public.vendas set estado = 'Anulada' where id = p_venda_id;
end;
$$;

