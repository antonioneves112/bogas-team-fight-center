-- =========================================================================
-- 03_VENDAS_STOCK.SQL — Gestão de produtos, stock e vendas
-- Requer 01_preparar.sql (usa public.is_treinador()).
-- Só acrescenta tabelas/funções novas: não mexe em nada do que já existe.
-- Idempotente: pode correr-se mais do que uma vez.
