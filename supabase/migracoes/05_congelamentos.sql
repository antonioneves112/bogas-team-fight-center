-- =========================================================================
-- 05_CONGELAMENTOS.SQL — Congelar sócios (lesão, férias, pausa)
-- Congela-se por MESES INTEIROS: de mes_inicio a mes_fim (inclusive, 'YYYY-MM').
-- Nesses meses o sócio não deve mensalidade. Volta a pagar sozinho no mês
-- seguinte a mes_fim (não é preciso nenhuma tarefa automática: é só a data).
-- Requer 01_preparar.sql (is_treinador) e 04 (portal_resumo). Idempotente.
-- =========================================================================

create table if not exists public.socio_congelamentos (
  id bigint generated by default as identity primary key,
  socio_id bigint not null references public.socios (id) on delete cascade,
  mes_inicio text not null check (mes_inicio ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  mes_fim text not null check (mes_fim ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  motivo text not null default 'Pausa' check (motivo in ('Lesão', 'Férias', 'Pausa', 'Outro')),
  notas text,
  treinador text,
  criado_em timestamptz not null default now(),
  check (mes_fim >= mes_inicio)
);
create index if not exists socio_congelamentos_socio_idx on public.socio_congelamentos (socio_id, mes_inicio, mes_fim);

alter table public.socio_congelamentos enable row level security;
revoke all on public.socio_congelamentos from anon;
drop policy if exists treinador_total on public.socio_congelamentos;
create policy treinador_total on public.socio_congelamentos for all to authenticated
  using (public.is_treinador()) with check (public.is_treinador());
grant select, insert, update, delete on public.socio_congelamentos to authenticated;

-- Não deixa dois congelamentos sobrepostos para o mesmo sócio.
create or replace function public._congelamento_sem_sobreposicao()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if exists (
    select 1 from public.socio_congelamentos c
    where c.socio_id = new.socio_id
      and c.id <> coalesce(new.id, -1)
      and c.mes_inicio <= new.mes_fim
      and c.mes_fim >= new.mes_inicio
  ) then
    raise exception 'CONGELAMENTO_SOBREPOSTO';
  end if;
  return new;
end;
$$;

drop trigger if exists congelamento_sem_sobreposicao on public.socio_congelamentos;
create trigger congelamento_sem_sobreposicao
  before insert or update on public.socio_congelamentos
  for each row execute function public._congelamento_sem_sobreposicao();

-- Portal: o resumo passa a dizer se o atleta está congelado no mês.
create or replace function public.portal_resumo(p_token text, p_mes text, p_hoje date)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, extensions
as $$
declare
  v_socio bigint := public._socio_da_sessao(p_token);
begin
  return jsonb_build_object(
    'socio', public._socio_publico(v_socio),
    'faturas_mes', coalesce((
      select jsonb_agg(jsonb_build_object('estado', m.estado, 'tipo', m.tipo))
      from public.mensalidades m
      where m.socio_id = v_socio and m.mes_ano = p_mes), '[]'::jsonb),
    'tem_aula_por_pagar', exists (
      select 1 from public.aulas_particulares a
      where a.socio_id = v_socio and a.estado = 'Aceite' and a.pago = false
        and a.data_aula::date < p_hoje),
    'proxima_aula', (
      select jsonb_build_object('data_aula', a.data_aula, 'hora_aula', a.hora_aula, 'estado', a.estado)
      from public.aulas_particulares a
      where a.socio_id = v_socio and a.data_aula::date >= p_hoje
      order by a.data_aula::date asc
      limit 1),
    'congelamento', (
      select jsonb_build_object('mes_inicio', c.mes_inicio, 'mes_fim', c.mes_fim, 'motivo', c.motivo)
      from public.socio_congelamentos c
      where c.socio_id = v_socio and c.mes_inicio <= p_mes and c.mes_fim >= p_mes
      limit 1),
    'notificacoes', coalesce((
      select jsonb_agg(to_jsonb(n) order by n.created_at desc)
      from public.notificacoes n
      where n.socio_id = v_socio), '[]'::jsonb)
  );
end;
$$;

grant execute on function public.portal_resumo(text, text, date) to anon, authenticated;
